import { ApiProperty, PartialType } from "@nestjs/swagger";
import { Transform, type TransformFnParams, Type } from "class-transformer";
import {
  ArrayMaxSize,
  ArrayMinSize,
  IsArray,
  IsBoolean,
  IsEnum,
  IsInt,
  IsObject,
  IsOptional,
  IsString,
  IsUUID,
  MaxLength,
  MinLength,
  ValidateNested,
} from "class-validator";

import { FORM_LIMITS, FormFieldType } from "@api/modules/events/forms/form-fields";
import { DateTransform, IsValidDate } from "utilities/nest/class-validator";

const trim = ({ value }: TransformFnParams) => (typeof value === "string" ? value.trim() : value);

export class FormFieldDefinition {
  /**
   * Stable field ID generated by the client, answers are keyed by it
   */
  @IsUUID()
  id: string;

  @ApiProperty({ enum: FormFieldType, enumName: "FormFieldType" })
  @IsEnum(FormFieldType)
  type: FormFieldType;

  @Transform(trim)
  @IsString()
  @MinLength(1)
  @MaxLength(FORM_LIMITS.maxLabelLength)
  label: string;

  @IsOptional()
  @IsString()
  @MaxLength(FORM_LIMITS.maxDescriptionLength)
  description?: string;

  @IsBoolean()
  required: boolean;

  /**
   * Choices for `singleSelect` and `multiSelect`, ignored for other types
   */
  @IsOptional()
  @IsArray()
  @ArrayMaxSize(FORM_LIMITS.maxOptions)
  @IsString({ each: true })
  @MaxLength(FORM_LIMITS.maxOptionLength, { each: true })
  options?: string[];
}

export class CreateEventForm {
  @Transform(trim)
  @IsString()
  @MinLength(1)
  @MaxLength(FORM_LIMITS.maxNameLength)
  name: string;

  @IsOptional()
  @IsString()
  @MaxLength(FORM_LIMITS.maxDescriptionLength)
  description?: string | null;

  /**
   * Shown as required to applicants, nothing is blocked when not filled
   */
  @IsBoolean()
  required: boolean;

  /**
   * @example 2026-12-20T23:59:59.000Z
   */
  @IsValidDate()
  @Transform(DateTransform)
  deadline: Date;

  @ApiProperty({ type: [FormFieldDefinition] })
  @IsArray()
  @ArrayMinSize(1)
  @ArrayMaxSize(FORM_LIMITS.maxFields)
  @ValidateNested({ each: true })
  @Type(() => FormFieldDefinition)
  fields: FormFieldDefinition[];
}

export class UpdateEventForm extends PartialType(CreateEventForm) {}

export class ReorderEventForms {
  /**
   * Every form ID of the event exactly once, in the new order
   */
  @IsArray()
  @IsInt({ each: true })
  formIds: number[];
}

export class SubmitEventFormResponse {
  /**
   * Answers keyed by field ID
   */
  @ApiProperty({ type: "object", additionalProperties: true })
  @IsObject()
  answers: Record<string, unknown>;
}
